/* NODE_PATH=/tmp/faultline-browser/node_modules node scripts/browser-check-v2.cjs */
const {chromium}=require('playwright');
const fs=require('node:fs');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1080}});const errors=[];page.on('pageerror',e=>errors.push(String(e)));
 await page.goto(process.env.FAULTLINE_URL||'http://127.0.0.1:8017');
 await page.getByRole('heading',{name:/Break your agents/}).waitFor();
 await page.getByRole('button',{name:'Benchmark lab',exact:true}).click();
 await page.getByRole('checkbox',{name:/Graph \/ structured/}).check();
 await page.getByRole('checkbox',{name:/Slow model on call two/}).check();
 await page.getByLabel('Repetitions per condition').fill('3');
 await page.getByRole('button',{name:'Run benchmark',exact:true}).click();
 await page.getByRole('heading',{name:'Execution records'}).waitFor();
 await page.locator('.live-events div').first().waitFor();
 await page.screenshot({path:'docs/screenshots/live-v2.png',fullPage:true});
 await page.waitForFunction(()=>document.body.innerText.includes('27 / 27 finished'),{},{timeout:125000});
 await page.getByRole('button',{name:'Overview',exact:true}).click();
 await page.screenshot({path:'docs/screenshots/overview-v2.png',fullPage:true});
 await page.getByRole('button',{name:'Leaderboard',exact:true}).click();
 await page.getByRole('heading',{name:'Reliability, beyond an average'}).waitFor();
 await page.locator('table tbody tr').nth(2).waitFor();
 const slider=page.getByLabel('S score weight');const before=await slider.inputValue();await slider.focus();await slider.press('ArrowRight');if(await slider.inputValue()===before)throw Error('Weight control disconnected');
 await page.getByLabel('Leaderboard tier',{exact:true}).selectOption('1');
 await page.getByRole('button',{name:'Runs',exact:true}).first().click();
 await page.locator('.run-chip').first().waitFor();
 await page.screenshot({path:'docs/screenshots/leaderboard-v2.png',fullPage:true});
 await page.getByRole('button',{name:'Compare agents',exact:true}).click();
 await page.getByRole('heading',{name:'One task. Every repeat.'}).waitFor();
 if(await page.locator('.repeat-square').count()!==9)throw Error('Repeat grid does not show all 3x3 baseline observations');
 await page.locator('.repeat-square').first().click();
 await page.locator('.grading-panel').waitFor();
 await page.getByText('Why this run received its verdict',{exact:true}).waitFor();
 await page.locator('.event summary').first().click();
 await page.screenshot({path:'docs/screenshots/inspector-v2.png',fullPage:true});
 await page.getByRole('button',{name:'Counterfactual',exact:true}).click();
 const selector=page.getByRole('combobox',{name:'Select faulted run'});
 const option=await selector.locator('option').filter({hasText:/M3/}).first().getAttribute('value');
 await selector.selectOption(option);
 await page.locator('.comparison-row').first().waitFor();
 if(!await page.getByText(/aligned row/).count())throw Error('Latency intervention did not show observed divergence');
 await page.screenshot({path:'docs/screenshots/counterfactual-v2.png',fullPage:true});
 await page.getByRole('button',{name:'Fault matrix',exact:true}).click();await page.locator('.matrix-cell').first().click();
 await page.getByRole('heading',{name:'Observable execution'}).waitFor();
 await page.getByRole('button',{name:'Run report',exact:true}).click();
 const download=page.waitForEvent('download');await page.getByRole('link',{name:'Export JSON'}).click();await download;
 const popup=page.waitForEvent('popup');await page.getByRole('link',{name:'Readable HTML report'}).click();const report=await popup;await report.waitForLoadState();if(!await report.getByRole('heading',{name:/FAULTLINE/}).count())throw Error('HTML report failed');await report.close();
 await page.reload();await page.getByRole('heading',{name:/Break your agents/}).waitFor();await page.getByRole('combobox').first().selectOption({index:1});await page.waitForTimeout(500);
 await page.setViewportSize({width:390,height:844});await page.screenshot({path:'docs/screenshots/mobile-v2.png',fullPage:true});
 if(errors.length)throw Error(errors.join('\n'));
 fs.writeFileSync('docs/browser-check-v2.json',JSON.stringify({passed:true,experiment_runs:27,agents:3,repetitions:3,conditions:['baseline','search_failure','M3'],checks:['live SSE','actual 20s latency intervention','pass^3 display','leaderboard filter','score weight control','source-run drilldown','3x3 repeat grid','grader panel','trace expansion','paired first divergence','matrix navigation','JSON download','HTML report','reload','mobile rendering'],pageErrors:errors},null,2)+'\n');
 console.log('Browser v2 checks passed (27 actual subprocess runs including nine 20-second latency interventions)');await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
